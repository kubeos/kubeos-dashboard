# ---------------------------------------------------------------------------- passwords
_libcrypt = None


def _crypt(word: str, salt: str) -> str | None:
    """crypt(3) through libcrypt; python3.13 removed the `crypt` module."""
    global _libcrypt
    if _libcrypt is None:
        name = ctypes.util.find_library("crypt") or "libcrypt.so.1"
        _libcrypt = ctypes.CDLL(name)
        _libcrypt.crypt.restype = ctypes.c_char_p
        _libcrypt.crypt.argtypes = [ctypes.c_char_p, ctypes.c_char_p]
    out = _libcrypt.crypt(word.encode(), salt.encode())
    return out.decode() if out else None


def shadow_hash(user: str) -> str | None:
    try:
        with open(SHADOW, "r", encoding="utf-8", errors="replace") as handle:
            for line in handle:
                fields = line.rstrip("\n").split(":")
                if len(fields) > 1 and fields[0] == user:
                    return fields[1]
    except OSError:
        return None
    return None


def local_account(user: str) -> bool:
    """A login is for a person who owns this machine: root, or a member of `sudo`."""
    try:
        entry = pwd.getpwnam(user)
    except KeyError:
        return False
    if entry.pw_uid == 0:
        return True
    try:
        return user in grp.getgrnam("sudo").gr_mem
    except KeyError:
        return False


def password_ok(user: str, password: str) -> bool:
    if not user or not password or not local_account(user):
        return False
    stored = shadow_hash(user)
    # "!" and "*" are locked accounts; an empty hash means "no password", which is a machine
    # misconfiguration and must not become a blank login.
    if not stored or stored in ("!", "*") or stored.startswith("!") or len(stored) < 8:
        return False
    # The salt is everything up to the field after the algorithm prefix:
    #   $y$j9T$SALT$hash   ->   $y$j9T$SALT   |   classic 22-char DES/MD5 forms -> first 12
    # The salt is the algorithm fields plus the salt field itself, and `split("$")` on a hash
    # that STARTS with "$" yields an empty first element - so the fields start at index 1:
    #   $y$j9T$SALT$hash  ->  ['', 'y', 'j9T', 'SALT', 'hash']  ->  salt = $y$j9T$SALT
    # (getting this wrong makes crypt() return a value that can never match, i.e. every
    #  password is refused - measured 2026-11-12 on kubeos1 before the first fix).
    if stored.startswith("$"):
        fields = stored.split("$")[1:]
        if len(fields) >= 3:
            salt = "$" + "$".join(fields[:3])
        else:
            salt = stored
    else:
        salt = stored[:2]
    computed = _crypt(password, salt)
    return bool(computed) and hmac.compare_digest(computed, stored)


# ---------------------------------------------------------------------------- sessions
class Sessions:
    def __init__(self, key: bytes, hours: float) -> None:
        self.key = key
        self.ttl = hours * 3600.0

    def issue(self, user: str) -> str:
        payload = json.dumps({"u": user, "exp": time.time() + self.ttl, "n": secrets.token_hex(8)},
                             separators=(",", ":")).encode()
        body = base64.urlsafe_b64encode(payload).rstrip(b"=").decode()
        mac = hmac.new(self.key, body.encode(), hashlib.sha256).hexdigest()
        return f"{body}.{mac}"

    def verify(self, value: str) -> str | None:
        try:
            body, mac = value.rsplit(".", 1)
        except ValueError:
            return None
        expected = hmac.new(self.key, body.encode(), hashlib.sha256).hexdigest()
        if not hmac.compare_digest(mac, expected):
            return None
        try:
            data = json.loads(base64.urlsafe_b64decode(body + "=" * (-len(body) % 4)))
        except Exception:
            return None
        if not isinstance(data, dict) or float(data.get("exp", 0)) < time.time():
            return None
        return str(data.get("u") or "") or None


