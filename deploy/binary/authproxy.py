#!/usr/bin/env python3
"""KubeOS dashboard login gateway: a Proxmox-style login in front of Headlamp.

WHEN   installed by install.sh and started as `kubeos-dashboard-auth.service`. It owns the
       public HTTPS port (default 30443) and Headlamp is moved behind it on 127.0.0.1:30445.

WHY    Headlamp has no local login: it authenticates with the kubeconfig it was given, so
       today anyone who can reach :30443 is cluster-admin without typing anything. The user
       asked for the Proxmox behaviour - open the dashboard, get a login page, enter the
       node's root password, get in. Headlamp cannot do that by itself (its only built-in
       auth is OIDC or "paste a token"), so the login has to live in front of it.

WHY PYTHON STANDARD LIBRARY, WHY SHADOW: a node must not grow a new runtime for a login form,
       and `python3-pam` is not part of Debian's python3. The password is therefore checked
       against /etc/shadow with crypt(3) through ctypes - the same hash the login prompt uses.
       This is what the console service already does for TLS and the PTY: stdlib only.

WHY A COOKIE AND NOT HTTP BASIC: the browser has to carry the session through the frontend,
       the API proxy and WebSocket upgrades (exec, logs), and it must be able to log out.

SAFE   Re-runnable and stateless apart from the session key: no file is written, nothing is
       stored per user, and a restart only invalidates sessions.

Honest limits, on purpose:
  * it authenticates LOCAL accounts (root, or anyone in the `sudo` group). KubeOS ships only
    root, so in practice that is root and its install-time password;
  * /etc/shadow is read directly, so PAM's account rules (locked account, expiry notices) are
    not consulted - `!`/`*` hashes can never match, which covers a locked root;
  * one session key per machine, generated by install.sh: deleting it logs everybody out.
"""

