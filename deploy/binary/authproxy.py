def request_standalone(console_port: int, token_file: str) -> tuple[bool, str]:
    """Ask this node's console to make it a standalone node again (POST /action/standalone).

    The console owns the work (it starts a transient systemd unit, which survives the dashboard
    restarting underneath it) and holds the token; this only says "now". No Origin header is sent,
    so the console's same-origin rule is satisfied by construction.
    """
    token = ""
    try:
        with open(token_file, "r", encoding="utf-8") as handle:
            token = handle.read().strip()
    except OSError as reason:
        return False, f"console token unreadable ({reason})"
    connection = http.client.HTTPSConnection("127.0.0.1", console_port, timeout=30,
                                             context=UPSTREAM_TLS)
    try:
        connection.request("POST", "/action/standalone",
                           body=b"{}", headers={
                               "Authorization": f"Bearer {token}",
                               "Content-Type": "application/json",
                               "Content-Length": "2",
                               "Host": f"127.0.0.1:{console_port}",
                           })
        response = connection.getresponse()
        payload = response.read().decode("utf-8", "replace")
        return 200 <= response.status < 300, f"HTTP {response.status}: {payload.strip()[:200]}"
    except OSError as reason:
        return False, f"console did not answer ({reason})"
    finally:
        connection.close()


class Membership:
    """Is this machine still a NODE of the cluster its dashboard is configured for?

    WHY THIS EXISTS (user report 2026-11-12, twice): after a node was removed from the cluster,
    opening that machine's own dashboard showed the OTHER machine under Nodes - never itself.
    The cause is not rendering: deleting a Node object does not revoke the dashboard's
    credential, so `.6` keeps answering `kubectl get nodes` from `.5`'s API, and that list
    ("kubeos1") is correct data about a cluster this machine is no longer part of. Proxmox does
    not show this symptom because there the node's own state is local; here the only local truth
    is "does the API still know my name", so that is what the gateway asks.

    STATES, and why "unknown" is not "detached": a node whose API server is unreachable is still
    a member (the control plane may be restarting). Only an explicit NotFound, or a credential
    the API refuses, means "removed" - so unknown keeps exactly today's behaviour.
    """

    def __init__(self, kubeconfig: str, hostname: str, interval: float,
                 standalone_after: float = 0.0, on_detached=None) -> None:
        self.kubeconfig = kubeconfig or ""
        self.hostname = hostname
        self.interval = max(3.0, interval)
        # Seconds a machine must be CONTINUOUSLY detached before it rebuilds itself as a
        # standalone node. 0 disables that (the old behaviour: show the page and wait).
        self.standalone_after = max(0.0, standalone_after)
        self.on_detached = on_detached
        self.state = "unknown"
        self.detail = "checking whether this machine is a node of a cluster"
        self._detached_since = 0.0
        self._standalone_fired = False
        self._lock = threading.Lock()

    def _set(self, state: str, detail: str) -> None:
        with self._lock:
            if state != self.state:
                log(f"membership: {self.state} -> {state} ({detail or 'no detail'})")
            if state == "detached" and self.state != "detached":
                self._detached_since = time.monotonic()
                self._standalone_fired = False
            if state != "detached":
                self._detached_since = 0.0
            self.state = state
            self.detail = detail

    def _maybe_standalone(self) -> None:
        """Once the machine has been removed long enough, let it become a node of its own.

        WHY A DELAY: a node that merely lost the network is `unknown`, never `detached` (see
        probe()), but a control plane being restarted for a minute is `detached` for that minute.
        Waiting makes the difference between "somebody removed this node" and "the cluster is
        briefly down" visible in time, and the work is only done once per detached episode.
        """
        if not self.on_detached or self.standalone_after <= 0:
            return
        # A join looks like a removal for a few seconds (the node's own cluster is being thrown
        # away). It is not one, and this machine is busy with it.
        if join_in_progress()[0]:
            return
        with self._lock:
            if self.state != "detached" or self._standalone_fired:
                return
            if not self._detached_since or time.monotonic() - self._detached_since < self.standalone_after:
                return
            self._standalone_fired = True        # set before the call: never fire twice
        log(f"has been removed from its cluster for {int(self.standalone_after)}s - "
            "rebuilding this machine as a standalone node")
        ok, detail = self.on_detached()
        if ok:
            log(f"standalone bring-up started ({detail})")
        else:
            log(f"WARNING: could not start the standalone bring-up: {detail}")
            with self._lock:
                self._standalone_fired = False   # a failed start may be retried

    def snapshot(self) -> tuple[str, str]:
        with self._lock:
            return self.state, self.detail

    def standalone_in(self) -> int | None:
        """Seconds until this machine rebuilds itself, or None when that will not happen."""
        if self.standalone_after <= 0:
            return None
        with self._lock:
            if self.state != "detached" or not self._detached_since:
                return None
            left = self.standalone_after - (time.monotonic() - self._detached_since)
            return max(0, int(left))

    def probe(self) -> None:
        if not self.kubeconfig or not os.path.exists(self.kubeconfig):
            self._set("unknown", f"no kubeconfig at {self.kubeconfig or '(none)'} to ask with")
            return
        if not os.path.exists(KUBECTL):
            self._set("unknown", f"{KUBECTL} is not installed")
            return
        try:
            done = subprocess.run(
                [KUBECTL, "--kubeconfig", self.kubeconfig, "get", "node", self.hostname,
                 "-o", "name", "--request-timeout=8s", "--cache-dir", "/tmp/kubeos-auth-cache"],
                capture_output=True, text=True, timeout=30,
                # The unit runs with ProtectHome=yes and ProtectSystem=strict, so kubectl must
                # not try to read or write anything under $HOME; PrivateTmp=yes gives it a
                # writable /tmp for its discovery cache.
                env={"PATH": "/usr/bin:/bin", "HOME": "/tmp"},
            )
        except (OSError, subprocess.TimeoutExpired) as reason:
            self._set("unknown", f"could not run kubectl ({reason})")
            return
        stderr = (done.stderr or "").strip()
        if done.returncode == 0 and (done.stdout or "").strip():
            self._set("member", "this machine is a node of the cluster its dashboard points at")
        elif "NotFound" in stderr or "not found" in stderr:
            self._set("detached", stderr.splitlines()[-1] if stderr
                      else "the cluster does not know this node any more")
        else:
            # Unreachable API, TLS trouble, a refused login: unknowable, so leave the dashboard
            # alone rather than pretend the machine was removed.
            self._set("unknown", stderr.splitlines()[-1] if stderr
                      else "the API server did not answer")

    def _loop(self) -> None:
        while True:
            self.probe()
            self._maybe_standalone()
            time.sleep(self.interval)

    def start(self) -> None:
        threading.Thread(target=self._loop, name="kubeos-membership", daemon=True).start()


class Gateway(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"
    server_version = "kubeos-auth"
    # ThreadingHTTPServer starts a thread per connection, so a socket that is opened and then
    # dribbled must not be held for ever: this is the only port that answers with the login
    # page, and a slowloris there would keep the operator out of their own node.
    timeout = 30

    membership: Membership
    console_port: int = 30444
    console_token_file: str = "/etc/kubeos-dashboard/console.token"

    sessions: Sessions
    upstream_port: int
    hostname: str = socket.gethostname()
    # Served WITHOUT a login on purpose: a browser has to trust the CA before it can show
    # anything else, and a certificate is public information.
    ca_pem: bytes = b""
    ca_fingerprint: str = ""
    failures: dict[str, list[float]] = {}
    failures_lock = threading.Lock()

    # SECURITY (SECURITY-REVIEW.md S6): one place that adds the browser protections to every
    # response this gateway sends, proxied ones included. Only headers that cannot change how a
    # page renders: framing denied, no MIME sniffing, no referrer leak, HTTPS pinned. A full
    # Content-Security-Policy is deliberately NOT set here - it has to be tested in a browser
    # against Headlamp's bundle first, or a wrong policy blanks the UI.
    SECURITY_HEADERS = (
        ("X-Frame-Options", "DENY"),
        ("X-Content-Type-Options", "nosniff"),
        ("Referrer-Policy", "no-referrer"),
        ("Content-Security-Policy", "frame-ancestors 'none'"),
        ("Strict-Transport-Security", "max-age=31536000"),
    )

    def end_headers(self):
        for key, value in self.SECURITY_HEADERS:
            self.send_header(key, value)
        super().end_headers()

    def log_message(self, fmt: str, *args) -> None:
        log(f"{self.client_address[0]} {fmt % args}")

    # -- helpers -----------------------------------------------------------------
    def _cookie_user(self) -> str | None:
        raw = self.headers.get("Cookie") or ""
        for part in raw.split(";"):
            name, _, value = part.strip().partition("=")
            if name == SESSION_COOKIE and value:
                return self.sessions.verify(value)
        return None

    def _send(self, code: int, body: bytes, content_type: str = "text/html; charset=utf-8",
              extra: list[tuple[str, str]] | None = None) -> None:
        self.send_response(code)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        for key, value in extra or []:
            self.send_header(key, value)
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(body)

    def _busy(self, reason: str) -> None:
        """Headlamp is not answering: during a join that is normal, so say so instead of 502."""
        wants_json = (
            self.path.startswith("/clusters/")
            and "text/html" not in (self.headers.get("Accept") or "")
        )
        log(f"{self.client_address[0]} upstream is down ({reason}) - serving the busy page")
        if wants_json:
            self._send(503, b'{"error":"the dashboard on this node is restarting"}\n',
                       content_type="application/json; charset=utf-8")
            return
        page = BUSY_PAGE.replace("__REASON__", reason).encode()
        self._send(503, page)

    def _login_page(self, error: str = "", user: str = "root") -> bytes:
        if self.ca_fingerprint:
            cert = ('Certificate: <strong>KubeOS Cluster CA</strong> &middot; '
                    f'<a href="/kubeos-ca.crt">download</a><br>'
                    f'SHA-256 <code>{self.ca_fingerprint}</code><br>'
                    'Browser warning? Import that file once as a trusted authority '
                    '(on the node: <code>kubeos-trust-ca</code> prints the exact steps).')
        else:
            cert = "Certificate: this node serves a self-signed certificate (no cluster CA)."
        # user/error come from the posted form, so escaping them is what stops this page from
        # reflecting markup. Measured 2026-11-13 before the fix: `user=" autofocus
        # onfocus="alert(1)` produced a live event-handler attribute and
        # `user="><script>alert(1)</script>` was echoed verbatim - one form post away from
        # script running as the signed-in cluster admin, on this origin.
        return (LOGIN_PAGE.replace("__HOST__", html.escape(self.hostname, quote=True))
                .replace("__USER__", html.escape(user, quote=True))
                .replace("__ERROR__", html.escape(error))
                .replace("__CERT__", cert)).encode()

    def _standalone_page(self) -> bytes:
        return STANDALONE_PAGE.replace("__HOST__", self.hostname).encode()

    def _send_json(self, code: int, payload: dict) -> None:
        self._send(code, (json.dumps(payload) + "\n").encode(),
                   content_type="application/json; charset=utf-8")

    def _console_request(self, method: str, path: str, body: bytes | None = None) -> None:
        """Ask THIS node's console service, with its token - which never reaches the browser.

        Server-side on purpose: the token is a root-PTY credential, the browser has no business
        holding it, and this hop has no Origin header, so the console's same-origin rule (which
        is what keeps every dashboard scoped to its own machine) is satisfied by construction.
        """
        token = ""
        try:
            with open(self.console_token_file, "r", encoding="utf-8") as handle:
                token = handle.read().strip()
        except OSError as reason:
            self._send_json(503, {"ok": False,
                                  "error": f"the console token {self.console_token_file} is "
                                           f"unreadable ({reason})"})
            return
        headers = {"Authorization": f"Bearer {token}", "Host": f"127.0.0.1:{self.console_port}"}
        if body is not None:
            headers["Content-Type"] = "application/json"
            headers["Content-Length"] = str(len(body))
        connection = http.client.HTTPSConnection("127.0.0.1", self.console_port, timeout=90,
                                                 context=UPSTREAM_TLS)
        try:
            connection.request(method, path, body=body, headers=headers)
            response = connection.getresponse()
            payload = response.read()
            status = response.status
        except OSError as reason:
            connection.close()
            self._send_json(503, {"ok": False,
                                  "error": f"this node's console service did not answer ({reason})"})
            return
        connection.close()
        self._send(status, payload, content_type="application/json; charset=utf-8")

    # -- rebalancing workloads onto the nodes that have room ------------------
    def _rebalance_plan(self) -> tuple[list, list, int, str]:
        """Compute, per workload, which pods sit on an over-full node.

        WHY NOT `rollout restart`: measured on a 4-node cluster (2026-11-13), a rolling update
        replaces pods while the old ones still exist, so the scheduler keeps seeing the crowded
        nodes as busy and the workload ends up wherever it happened to fit - 1/2/1/0 instead of
        1/1/1/1. Deleting ONLY the surplus pods is what moves them: the controller recreates them
        while the crowded node's pod is gone, the scheduler's spread rules then get a say, and the
        rest of the workload keeps running untouched.
        """
        conf = self.membership.kubeconfig
        ok, nodes, error = kubectl_json(conf, "get", "nodes", "-o", "json")
        if not ok:
            raise RuntimeError(f"cannot list the nodes: {error}")
        ok, pods, error = kubectl_json(conf, "get", "pods", "-A", "-o", "json")
        if not ok:
            raise RuntimeError(f"cannot list the pods: {error}")

        eligible = []
        for item in nodes.get("items", []):
            meta = item.get("metadata") or {}
            spec = item.get("spec") or {}
            status = item.get("status") or {}
            ready = any(cond.get("type") == "Ready" and cond.get("status") == "True"
                        for cond in (status.get("conditions") or []))
            taints = [t.get("effect") for t in (spec.get("taints") or [])]
            if ready and not spec.get("unschedulable") and not (
                    {"NoSchedule", "NoExecute"} & set(taints)):
                eligible.append(meta.get("name") or "")
        eligible = [name for name in eligible if name]

        bare = 0
        pods_by_owner: dict = {}
        for pod in pods.get("items", []):
            status = pod.get("status") or {}
            if (status.get("phase") or "") in ("Succeeded", "Failed"):
                continue
            owners = (pod.get("metadata") or {}).get("ownerReferences") or []
            if not owners:
                bare += 1
                continue
            if pod.get("metadata", {}).get("deletionTimestamp"):
                continue
            # A Deployment's pods are owned by its ReplicaSet, so walk one level up.
            owner = owners[0]
            key = (owner.get("kind") or "", owner.get("name") or "", pod["metadata"].get("namespace") or "default")
            pods_by_owner.setdefault(key, []).append(pod)

        # ReplicaSet -> Deployment, so the plan can talk about workloads the user recognises.
        rs_to_deploy: dict = {}
        ok, sets, _ = kubectl_json(conf, "get", "replicasets", "-A", "-o", "json")
        if ok:
            for item in sets.get("items", []):
                meta = item.get("metadata") or {}
                for owner in (meta.get("ownerReferences") or []):
                    if owner.get("kind") == "Deployment":
                        rs_to_deploy[(meta.get("namespace") or "default", meta.get("name") or "")] = owner.get("name") or ""

        workloads, plan = [], []
        for resource, kind in (("deployments", "Deployment"), ("statefulsets", "StatefulSet")):
            ok, listing, _ = kubectl_json(conf, "get", resource, "-A", "-o", "json")
            if not ok:
                continue
            for item in listing.get("items", []):
                meta = item.get("metadata") or {}
                spec = item.get("spec") or {}
                status = item.get("status") or {}
                replicas = int(spec.get("replicas") or 0)
                if replicas <= 0:
                    continue
                namespace = meta.get("namespace") or "default"
                name = meta.get("name") or ""
                owned = pods_by_owner.get((kind, name, namespace), [])
                if kind == "Deployment":
                    owned = []
                    for (owner_kind, owner_name, owner_ns), owned_pods in pods_by_owner.items():
                        if owner_kind == "ReplicaSet" and owner_ns == namespace and \
                                rs_to_deploy.get((namespace, owner_name)) == name:
                            owned.extend(owned_pods)
                placement: dict = {}
                for pod in owned:
                    node = (pod.get("spec") or {}).get("nodeName") or ""
                    if node:
                        placement[node] = placement.get(node, 0) + 1
                # Target: as even as possible over the nodes that can take pods.
                targets: dict = {}
                if eligible:
                    base, extra = divmod(replicas, len(eligible))
                    ordered = sorted(eligible, key=lambda n: (-placement.get(n, 0), n))
                    for index, node in enumerate(ordered):
                        targets[node] = base + (1 if index < extra else 0)
                # Keep up to `allowed` pods where they are and move the rest; documents what the
                # user sees in the preview ("2 pods will move off kubeos1").
                moves = []
                for node, count in placement.items():
                    allowed = targets.get(node, count)
                    if count <= allowed:
                        continue
                    on_node = [pod for pod in owned
                               if (pod.get("spec") or {}).get("nodeName") == node]
                    moves.extend(on_node[allowed:])
                workloads.append({"kind": kind, "namespace": namespace, "name": name,
                                  "replicas": replicas,
                                  "ready": int(status.get("readyReplicas") or 0),
                                  "placement": placement,
                                  "would_move": len(moves)})
                for pod in moves:
                    plan.append((namespace, pod.get("metadata", {}).get("name") or "", kind, name))
        return workloads, plan, bare, ""

    def _rebalance_preview(self) -> None:
        try:
            workloads, plan, bare, _ = self._rebalance_plan()
        except RuntimeError as reason:
            self._send_json(503, {"ok": False, "error": str(reason)})
            return
        self._send_json(200, {"ok": True, "annotation": REBALANCE_ANNOTATION,
                              "workloads": workloads, "would_move": len(plan),
                              "bare_pods": bare})
        return

    def _rebalance_apply(self) -> None:
        """Delete ONLY the pods sitting on over-full nodes; their controller recreates them.

        Nothing is created here: the workload's own controller makes the replacement, exactly as
        it does when a node is removed. The pods left alone never restart.
        """
        origin = (self.headers.get("Origin") or "").strip()
        if origin:
            host = (self.headers.get("Host") or "").strip()
            if host and origin not in (f"https://{host}", f"http://{host}"):
                # The session cookie would otherwise let any page on the internet move the user's
                # pods with a form post.
                self._send_json(403, {"ok": False, "error": "cross-origin request refused"})
                return
        try:
            workloads, plan, bare, _ = self._rebalance_plan()
        except RuntimeError as reason:
            self._send_json(503, {"ok": False, "error": str(reason)})
            return
        conf = self.membership.kubeconfig
        moved, failed = [], []
        for namespace, pod_name, kind, workload in plan:
            ok, error = kubectl_run(
                conf, "-n", namespace, "delete", "pod", pod_name,
                "--grace-period=1", "--wait=false", timeout=30)
            entry = {"namespace": namespace, "pod": pod_name,
                     "workload": f"{kind}/{workload}"}
            if ok:
                moved.append(entry)
            else:
                failed.append({**entry, "error": error})
        log(f"{self.client_address[0]} rebalanced: deleting {len(moved)} pod(s), "
            f"{len(failed)} failure(s)")
        self._send_json(200, {"ok": True, "moved": moved, "failed": failed,
                              "bare_pods": bare, "workloads": workloads})

    def _standalone(self, path: str) -> None:
        """The detached machine's own view: itself, and a way back into a cluster."""
        if path == "/kubeos-standalone/state":
            state, detail = self.membership.snapshot()
            joining, join_detail = join_in_progress()
            if joining:
                state, detail = "joining", join_detail or "joining this machine to a cluster"
            elif standalone_bringup_in_progress():
                # The automatic rebuild (option A) is the other way this page's machine gets its
                # dashboard back, and it used to show nothing while it ran.
                state = "rebuilding"
                detail = ("this machine is rebuilding its own one-node cluster; the dashboard "
                          "comes back by itself when that is done")
            remaining = self.membership.standalone_in()
            self._send_json(200, {"state": state, "detail": detail, "node": self.hostname,
                                  "standalone_in": remaining,
                                  "standalone_after": self.membership.standalone_after})
            return
        if path == "/kubeos-standalone/node":
            self._console_request("GET", "/node")
            return
        if path == "/kubeos-standalone/join":
            if self.command in ("GET", "HEAD"):
                self._console_request("GET", "/action/join")
                return
            if self.command != "POST":
                self._send_json(405, {"ok": False, "error": "POST a join string here"})
                return
            if self.membership.snapshot()[0] != "detached":
                # A join wipes this machine's cluster. Only offer it when there is nothing left
                # to wipe; otherwise the dashboard's own Join page is the right door.
                self._send_json(409, {"ok": False,
                                      "error": "this machine is already a node of a cluster - "
                                               "open its dashboard and use Join node"})
                return
            length = int(self.headers.get("Content-Length") or 0)
            if length <= 0 or length > 32768:
                self._send_json(400, {"ok": False, "error": "expected a small JSON body"})
                return
            self._console_request("POST", "/action/join", self.rfile.read(length))
            return
        if self.command in ("GET", "HEAD"):
            self._send(200, self._standalone_page())
            return
        self._send_json(404, {"ok": False, "error": "not found"})

    def _failure_count(self) -> int:
        """Wrong passwords from this address inside the window (prunes while it counts)."""
        now = time.time()
        address = self.client_address[0]
        with self.failures_lock:
            hits = [t for t in self.failures.get(address, []) if now - t < FAIL_WINDOW]
            if hits:
                self.failures[address] = hits
            else:
                # Do not keep an address (personal data) for a client that stopped trying.
                self.failures.pop(address, None)
            return len(hits)

    def _record_failure(self) -> None:
        with self.failures_lock:
            self.failures.setdefault(self.client_address[0], []).append(time.time())

    def _clear_failures(self) -> None:
        with self.failures_lock:
            self.failures.pop(self.client_address[0], None)

    # -- login / logout ----------------------------------------------------------
    def _handle_login(self) -> None:
        length = int(self.headers.get("Content-Length") or 0)
        if length <= 0 or length > 4096:
            self._send(400, self._login_page("That form was empty."))
            return
        fields = parse_qs(self.rfile.read(length).decode("utf-8", "replace"))
        user = (fields.get("user") or [""])[0].strip()
        password = (fields.get("password") or [""])[0]
        # THE RATE LIMIT MUST NEVER REFUSE THE CORRECT PASSWORD. It used to run before the
        # password was verified, so five wrong guesses from one address locked the real admin
        # out for five minutes - and any stranger who could reach :30443 could do that on
        # demand (measured 2026-11-13: five 401s, then 429 - including for the correct
        # password). Now 429 answers WRONG passwords only, and a hard cap stops the password
        # check itself from being used as a CPU lever.
        failures = self._failure_count()
        if failures >= FAIL_HARD_LIMIT:
            log(f"{self.client_address[0]} refused: {failures} failed logins, not verifying")
            self._send(429, self._login_page("Too many attempts - wait a few minutes."),
                       extra=[("Retry-After", "300")])
            return
        if not password_ok(user, password):
            self._record_failure()
            log(f"{self.client_address[0]} refused: bad password for {user or '(no user)'}")
            if failures + 1 >= FAIL_LIMIT:
                self._send(429, self._login_page("Too many attempts - wait a few minutes."),
                           extra=[("Retry-After", "300")])
            else:
                self._send(401, self._login_page("Wrong user or password.", user=user or "root"))
            return
        self._clear_failures()
        cookie = (f"{SESSION_COOKIE}={self.sessions.issue(user)}; Path=/; HttpOnly; Secure; "
                  f"SameSite=Strict; Max-Age={int(self.sessions.ttl)}")
        log(f"{self.client_address[0]} signed in as {user}")
        self._send(303, b"", extra=[("Location", "/"), ("Set-Cookie", cookie)])

    def _handle_logout(self) -> None:
        cookie = (f"{SESSION_COOKIE}=; Path=/; HttpOnly; Secure; SameSite=Strict; Max-Age=0")
        self._send(303, b"", extra=[("Location", "/"), ("Set-Cookie", cookie)])

    # -- proxying ----------------------------------------------------------------
    def _is_websocket(self) -> bool:
        return "websocket" in (self.headers.get("Upgrade") or "").lower()

    def _tunnel(self, upstream: socket.socket) -> None:
        """Blind bidirectional copy once the upstream said 101."""
        peers = {self.connection: upstream, upstream: self.connection}
        try:
            while True:
                readable, _, _ = select.select([self.connection, upstream], [], [], 3600)
                if not readable:
                    return
                for source in readable:
                    data = source.recv(65536)
                    if not data:
                        return
                    peers[source].sendall(data)
        except OSError:
            return

    def _proxy(self) -> None:
        body = None
        try:
            length = int(self.headers.get("Content-Length") or 0)
        except ValueError:
            self._send(400, b"bad Content-Length\n", content_type="text/plain; charset=utf-8")
            return
        if length > MAX_BODY:
            self._send(413, b"request body too large\n",
                       content_type="text/plain; charset=utf-8")
            return
        if length > 0:
            body = self.rfile.read(length)

        if self._is_websocket():
            self._proxy_websocket()
            return

        headers = {k: v for k, v in self.headers.items()
                   if k.lower() not in HOP_BY_HOP and k.lower() not in CLIENT_SUPPLIED}
        headers["Host"] = f"127.0.0.1:{self.upstream_port}"
        headers["X-Forwarded-For"] = self.client_address[0]
        headers["X-Forwarded-Proto"] = "https"
        connection = http.client.HTTPSConnection("127.0.0.1", self.upstream_port, timeout=600,
                                                 context=UPSTREAM_TLS)
        try:
            connection.request(self.command, self.path, body=body, headers=headers)
            response = connection.getresponse()
        except OSError as reason:
            connection.close()
            self._busy(str(reason))
            return

        # Every HTML page from Headlamp gets the watchdog. Buffered on purpose: the body is the
        # SPA's index (a few KB), and a Content-Length that is off by the injected script's length
        # would truncate the page instead of fixing it.
        content_type = (response.getheader("Content-Type") or "").lower()
        if (self.command == "GET" and "text/html" in content_type
                and not self._is_websocket()):
            raw = response.read()
            connection.close()
            if WATCH_SNIPPET not in raw:
                if b"</body>" in raw:
                    raw = raw.replace(b"</body>", WATCH_SNIPPET + b"</body>", 1)
                else:
                    raw = raw + WATCH_SNIPPET
            self.send_response(response.status, response.reason)
            for key, value in response.getheaders():
                lower = key.lower()
                if lower in HOP_BY_HOP or lower == "content-length":
                    continue
                self.send_header(key, value)
            self.send_header("Content-Length", str(len(raw)))
            self.end_headers()
            self.wfile.write(raw)
            self.wfile.flush()
            return

        self.send_response(response.status, response.reason)
        forwarded_length = None
        for key, value in response.getheaders():
            lower = key.lower()
            if lower in HOP_BY_HOP and lower != "content-length":
                continue
            if lower == "content-length":
                forwarded_length = value
                continue
            self.send_header(key, value)
        if forwarded_length is not None:
            self.send_header("Content-Length", forwarded_length)
        elif self.command != "HEAD":
            # No length from upstream (a watch stream, a log follow). `http.client` gives us
            # decoded bytes, so re-frame them: dropping Transfer-Encoding without a length
            # would leave the browser unable to tell where the body ends.
            self.send_header("Transfer-Encoding", "chunked")
        self.end_headers()
        try:
            if self.command == "HEAD":
                self.wfile.flush()
            else:
                while True:
                    chunk = response.read(65536)
                    if not chunk:
                        break
                    if forwarded_length is None:
                        self.wfile.write(f"{len(chunk):X}\r\n".encode() + chunk + b"\r\n")
                    else:
                        self.wfile.write(chunk)
                    self.wfile.flush()
                if forwarded_length is None:
                    self.wfile.write(b"0\r\n\r\n")
                self.wfile.flush()
        except OSError:
            pass
        finally:
            connection.close()

    def _proxy_websocket(self) -> None:
        upstream = UPSTREAM_TLS.wrap_socket(
            socket.create_connection(("127.0.0.1", self.upstream_port), timeout=30),
            server_hostname="127.0.0.1")
        lines = [f"{self.command} {self.path} HTTP/1.1"]
        for key, value in self.headers.items():
            if key.lower() in ("host", "proxy-connection"):
                continue
            lines.append(f"{key}: {value}")
        lines.append(f"Host: 127.0.0.1:{self.upstream_port}")
        upstream.sendall(("\r\n".join(lines) + "\r\n\r\n").encode())

        head = b""
        while b"\r\n\r\n" not in head:
            piece = upstream.recv(4096)
            if not piece:
                upstream.close()
                self._send(502, b"websocket upstream closed during the handshake\n",
                           content_type="text/plain; charset=utf-8")
                return
            head += piece
        header, rest = head.split(b"\r\n\r\n", 1)
        self.wfile.write(header + b"\r\n\r\n")
        if rest:
            self.wfile.write(rest)
        self.wfile.flush()
        self.close_connection = True
        status = header.split(b"\r\n", 1)[0]
        if b" 101 " in status:
            self._tunnel(upstream)
        upstream.close()

    # -- the node console, same-origin --------------------------------------------
    # WHY THIS EXISTS: the browser used to call the console directly on its own port, so it had
    # to accept a SECOND certificate exception (browsers treat each port as a separate site) and
    # a fetch failed silently until somebody opened that URL by hand. One origin means one
    # exception - the dashboard's - and the console becomes an internal hop this gateway makes.
    CONSOLE_PREFIX = "/console-api"

    def _console_target(self):
        """Where kubeos-console.service lives, and how to trust its certificate.

        CONFIGURED, NOT HARDCODED: KUBEOS_CONSOLE_URL (default https://127.0.0.1:30444),
        KUBEOS_CONSOLE_CA (default /etc/kubeos-dashboard/ca.crt) and
        KUBEOS_CONSOLE_TLS_VERIFY (default 1).

        THE CERTIFICATE IS STILL VERIFIED: the console presents a leaf signed by the cluster CA,
        which is the file this gateway already has. Only the NAME check is relaxed, because the
        hop dials 127.0.0.1 while the certificate carries the node's own address - that is not
        the same thing as switching verification off, and verification stays on everywhere else.
        """
        url = os.environ.get("KUBEOS_CONSOLE_URL", "https://127.0.0.1:30444")
        parsed = urlparse(url)
        host = parsed.hostname or "127.0.0.1"
        port = parsed.port or 30444
        verify = os.environ.get("KUBEOS_CONSOLE_TLS_VERIFY", "1").strip().lower() not in (
            "0", "false", "no")
        ca = os.environ.get("KUBEOS_CONSOLE_CA", "/etc/kubeos-dashboard/ca.crt")
        if not verify:
            context = ssl._create_unverified_context()
        else:
            context = ssl.create_default_context(cafile=ca if os.path.exists(ca) else None)
            context.check_hostname = False
        return host, port, context

    def _console_proxy(self) -> None:
        parsed = urlparse(self.path)
        rest = parsed.path[len(self.CONSOLE_PREFIX):] or "/"
        target = rest + (("?" + parsed.query) if parsed.query else "")
        try:
            length = int(self.headers.get("Content-Length") or 0)
        except ValueError:
            self._send(400, b"bad Content-Length\n", content_type="text/plain; charset=utf-8")
            return
        if length > MAX_BODY:
            self._send(413, b"request body too large\n",
                       content_type="text/plain; charset=utf-8")
            return
        body = self.rfile.read(length) if length > 0 else None
        host, port, context = self._console_target()
        # Pass-through on purpose: the page already holds the console token (it reads the
        # cluster Secret), so the authorization header travels untouched and this gateway never
        # has to store or log a credential. Access logs record the path WITHOUT the query, so a
        # token passed as ?token= (the WebSocket needs that form) never lands in the journal.
        headers = {k: v for k, v in self.headers.items()
                   if k.lower() not in HOP_BY_HOP and k.lower() not in CLIENT_SUPPLIED}
        headers["Host"] = f"{host}:{port}"
        headers["X-Forwarded-For"] = self.client_address[0]
        headers["X-Forwarded-Proto"] = "https"
        # The console accepts a handshake or an action only from its OWN origin: it compares the
        # hostname in Origin with the hostname in Host (console.py, "bad origin"). The browser's
        # origin is the dashboard now, so this trusted hop presents the console's own origin -
        # which keeps the console's CSRF check fully intact for anything talking to it directly
        # (measured 2026-11-21: Firefox got 403 "bad origin" while a client that sent no Origin
        # header got 101, which is why only a real browser showed this).
        for key in [k for k in headers if k.lower() == "origin"]:
            headers[key] = f"https://{host}:{port}"

        if self._is_websocket():
            self._console_websocket(host, port, context, target, headers)
            return

        connection = http.client.HTTPSConnection(host, port, timeout=600, context=context)
        try:
            connection.request(self.command, target, body=body, headers=headers)
            response = connection.getresponse()
        except OSError as reason:
            connection.close()
            self._send(502, f"the node console is not answering ({reason})\n".encode(),
                       content_type="text/plain; charset=utf-8")
            return
        self.send_response(response.status, response.reason)
        length_header = None
        for key, value in response.getheaders():
            lower = key.lower()
            if lower in HOP_BY_HOP and lower != "content-length":
                continue
            if lower == "content-length":
                length_header = value
                continue
            self.send_header(key, value)
        if length_header is not None:
            self.send_header("Content-Length", length_header)
        elif self.command != "HEAD":
            self.send_header("Transfer-Encoding", "chunked")
        self.end_headers()
        try:
            if self.command == "HEAD":
                self.wfile.flush()
            else:
                while True:
                    chunk = response.read(65536)
                    if not chunk:
                        break
                    if length_header is None:
                        self.wfile.write(f"{len(chunk):X}\r\n".encode() + chunk + b"\r\n")
                    else:
                        self.wfile.write(chunk)
                    self.wfile.flush()
                if length_header is None:
                    self.wfile.write(b"0\r\n\r\n")
                self.wfile.flush()
        except OSError:
            pass
        finally:
            connection.close()

    def _console_websocket(self, host, port, context, target, headers) -> None:
        """The terminal. A browser cannot set headers on a WebSocket, so the token is normally
        in the query string; either way it is forwarded untouched and never logged."""
        try:
            upstream = context.wrap_socket(socket.create_connection((host, port), timeout=30),
                                           server_hostname=host)
        except OSError as reason:
            self._send(502, f"the node console is not answering ({reason})\n".encode(),
                       content_type="text/plain; charset=utf-8")
            return
        lines = [f"{self.command} {target} HTTP/1.1"]
        for key, value in headers.items():
            if key.lower() in ("host", "proxy-connection"):
                continue
            lines.append(f"{key}: {value}")
        lines.append(f"Host: {host}:{port}")
        upstream.sendall(("\r\n".join(lines) + "\r\n\r\n").encode())

        head = b""
        while b"\r\n\r\n" not in head:
            piece = upstream.recv(4096)
            if not piece:
                upstream.close()
                self._send(502, b"the console closed the websocket during the handshake\n",
                           content_type="text/plain; charset=utf-8")
                return
            head += piece
        header, rest = head.split(b"\r\n\r\n", 1)
        self.wfile.write(header + b"\r\n\r\n")
        if rest:
            self.wfile.write(rest)
        self.wfile.flush()
        self.close_connection = True
        if b" 101 " in header.split(b"\r\n", 1)[0]:
            self._tunnel(upstream)
        upstream.close()

    # -- routing -----------------------------------------------------------------
    def _dispatch(self) -> None:
        path = urlparse(self.path).path
        if path == "/kubeos-login":
            if self.command != "POST":
                self._send(405, self._login_page(), extra=[("Allow", "POST")])
                return
            self._handle_login()
            return
        if path in ("/kubeos-logout", "/logout"):
            self._handle_logout()
            return
        if path == "/kubeos-ca.crt" and self.ca_pem:
            self._send(200, self.ca_pem, content_type="application/x-x509-ca-cert",
                       extra=[("Content-Disposition", "attachment; filename=kubeos-ca.crt")])
            return
        if path == "/kubeos-node":
            # Which node is SERVING this page. Public on purpose: a hostname is not a secret
            # and the login page needs it too. Without it a browser cannot tell "which node am
            # I on" from "which cluster am I looking at" - the confusion that made a worker look
            # like it had been replaced by the control plane (2026-11-12).
            body = json.dumps({"node": self.hostname}).encode()
            self._send(200, body, content_type="application/json; charset=utf-8")
            return
        if path == "/healthz":
            self._send(200, b"ok\n", content_type="text/plain; charset=utf-8")
            return

        user = self._cookie_user()
        if not user:
            wants_html = "text/html" in (self.headers.get("Accept") or "") or path == "/"
            if self.command in ("GET", "HEAD") and wants_html:
                self._send(401 if path != "/" else 200, self._login_page())
            else:
                self._send(401, b'{"error":"not signed in"}\n',
                           content_type="application/json; charset=utf-8")
            return

        if path == "/console-api" or path.startswith("/console-api/"):
            # Same-origin console (2026-11-21): one certificate for the whole product. Behind the
            # login gate, because every console route is a root action on this node.
            self._console_proxy()
            return


        if path == "/kubeos-node-health":
            state, detail = self.membership.snapshot()
            self._send_json(200, host_health(state, detail))
            return

        if path == "/kubeos-watch.js":
            self._send(200, WATCH_JS, content_type="application/javascript; charset=utf-8")
            return

        if path == "/kubeos-cluster-health":
            state, detail = self.membership.snapshot()
            # "member" is exactly what the probe says after asking THIS node's API server for this
            # node's own object: an answer means the cluster is reachable from here.
            reachable = state == "member"
            self._send_json(200, {"ok": True, "api_reachable": reachable,
                                  "state": state,
                                  "detail": "" if reachable else
                                  (detail or "the cluster API is not answering")})
            return

        if path == "/kubeos-rebalance":
            # Behind the login gate on purpose: this restarts the user's workloads.
            if self.command in ("POST", "PUT"):
                self._rebalance_apply()
            else:
                self._rebalance_preview()
            return

        if path.startswith("/kubeos-standalone"):
            self._standalone(path)
            return

        joining, join_detail = join_in_progress()
        if joining:
            # Announce the work instead of letting Headlamp paint its own red failure: the browser
            # keeps a spinner and simply reloads into the dashboard once the node is Ready.
            if self._is_websocket():
                self._send(503, b"this machine is joining a cluster\n",
                           content_type="text/plain; charset=utf-8")
                return
            wants_html = "text/html" in (self.headers.get("Accept") or "") or path == "/"
            if self.command in ("GET", "HEAD") and wants_html:
                step = join_detail or "waiting for the join to finish"
                # journal-derived text: escaped for the same reason as the login page
                self._send(200, (JOINING_PAGE.replace("__HOST__", html.escape(self.hostname, quote=True))
                                 .replace("__STEP__", html.escape(step))).encode())
            else:
                self._send_json(503, {"state": "joining",
                                      "error": "this machine is joining a cluster",
                                      "detail": join_detail})
            return

        if self.membership.snapshot()[0] == "detached":
            # THIS MACHINE IS NOT IN A CLUSTER ANY MORE, so proxying Headlamp would show somebody
            # else's cluster under its name - the exact report this exists to end ("after
            # removed kubeos2 ... it shows only kubeos1"). Show the machine itself instead.
            if self._is_websocket():
                self._send(503, b"this machine is not part of a cluster\n",
                           content_type="text/plain; charset=utf-8")
                return
            wants_html = "text/html" in (self.headers.get("Accept") or "") or path == "/"
            if self.command in ("GET", "HEAD") and wants_html:
                if standalone_bringup_in_progress():
                    # Option A is running right now: a progress page, not the frozen-looking
                    # "not part of a cluster" page whose machine is busy rebuilding itself.
                    self._send(200, REBUILDING_PAGE.replace("__HOST__", self.hostname).encode())
                    return
                self._send(200, self._standalone_page())
            else:
                self._send_json(503, {"error": "this machine is not part of a cluster",
                                      "node": self.hostname})
            return

        self._proxy()

    def do_GET(self) -> None:  # noqa: N802 - http.server naming
        self._dispatch()

    do_HEAD = do_GET
    do_POST = do_GET
    do_PUT = do_GET
    do_PATCH = do_GET
    do_DELETE = do_GET
    do_OPTIONS = do_GET


def main() -> int:
    parser = argparse.ArgumentParser(description="KubeOS dashboard login gateway")
    parser.add_argument("--listen", default="0.0.0.0")
    parser.add_argument("--port", type=int, default=30443)
    parser.add_argument("--upstream-port", type=int, default=30445)
    parser.add_argument("--tls-cert", required=True)
    parser.add_argument("--tls-key", required=True)
    parser.add_argument("--session-key", required=True)
    parser.add_argument("--session-hours", type=float, default=12.0)
    parser.add_argument("--ca-file", default="",
                        help="CA certificate to offer at /kubeos-ca.crt, so a browser can "
                             "trust every node with one import")
    parser.add_argument("--kubeconfig", default=DEFAULT_KUBECONFIG,
                        help="the kubeconfig this node's dashboard uses; the gateway asks it "
                             "whether the cluster still knows this machine's node name")
    parser.add_argument("--self-node", default="",
                        help="the node name to ask the cluster about (default: this hostname). "
                             "An override exists so both branches can be exercised on a healthy "
                             "cluster without removing a real node")
    parser.add_argument("--probe-interval", type=float, default=10.0,
                        help="seconds between membership probes (minimum 3)")
    parser.add_argument("--console-port", type=int, default=30444,
                        help="this node's console service, used by the detached page")
    parser.add_argument("--console-token-file", default="/etc/kubeos-dashboard/console.token",
                        help="the console token the detached page's join request needs")
    parser.add_argument("--standalone-after", type=float, default=120.0,
                        help="seconds a machine must be continuously removed from its cluster "
                             "before it rebuilds itself as a standalone node (0 disables)")
    args = parser.parse_args()

    try:
        with open(args.session_key, "r", encoding="utf-8") as handle:
            key = bytes.fromhex(handle.read().strip())
    except (OSError, ValueError) as reason:
        log(f"cannot read the session key {args.session_key}: {reason}")
        return 2
    if len(key) < 16:
        log("the session key is too short")
        return 2

    if args.ca_file:
        try:
            Gateway.ca_pem = open(args.ca_file, "rb").read()
        except OSError as reason:
            log(f"cannot read the CA file {args.ca_file}: {reason} (the download is disabled)")
            Gateway.ca_pem = b""
    else:
        Gateway.ca_pem = b""
    Gateway.ca_fingerprint = pem_fingerprint(Gateway.ca_pem) if Gateway.ca_pem else ""

    Gateway.sessions = Sessions(key, args.session_hours)
    Gateway.upstream_port = args.upstream_port
    Gateway.hostname = socket.gethostname()
    Gateway.console_port = args.console_port
    Gateway.console_token_file = args.console_token_file
    Gateway.membership = Membership(
        args.kubeconfig, args.self_node or Gateway.hostname, args.probe_interval,
        standalone_after=args.standalone_after,
        on_detached=lambda: request_standalone(args.console_port, args.console_token_file),
    )
    Gateway.membership.start()

    context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    context.minimum_version = ssl.TLSVersion.TLSv1_2
    context.load_cert_chain(args.tls_cert, args.tls_key)

    server = QuietServer((args.listen, args.port), Gateway)
    server.daemon_threads = True
    server.socket = context.wrap_socket(server.socket, server_side=True)
    log(f"listening on https://{args.listen}:{args.port}/ -> 127.0.0.1:{args.upstream_port} "
        f"(login as root with this node's password)")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    return 0


if __name__ == "__main__":
    sys.exit(main())
